import assert from "node:assert/strict";
import { mkdtemp, mkdir, rm, rmdir, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createTestAccount, TestBrowser } from "./reportAuthFixture.mjs";
import { campaignBrowser } from "./campaignBrowser.mjs";

let account, other, browser, temp;
const read = async api => (await api.request("/api/crm/library")).json();
const json = (api, url, method, data) => api.request(url, { method, headers: { "content-type": "application/json" }, body: JSON.stringify({ ...data, operationId: crypto.randomUUID() }) });
const put = (api, data) => json(api, "/api/crm/library", "PUT", data);
const post = (api, data) => json(api, "/api/analytics", "POST", data);
try {
  account = await createTestAccount();
  other = await createTestAccount();
  const api = new TestBrowser(), separate = new TestBrowser(), laptop = new TestBrowser();
  await Promise.all([api.signIn(account), separate.signIn(other), laptop.signIn(account)]);
  const library = await read(api);
  const empty = await read(separate);
  assert.equal(empty.data.clients.length, 0);
  assert.equal((await put(separate, empty)).status, 200);
  library.data.clients = [{ id: "synthetic-client", company: "Example Analytics", industry: "Software", location: "Pune", website: "https://example.com/", contacts: [],
    services: ["Meta Ads"], retainer: 0, contractStart: "", contractEnd: "", accountManagerId: account.id, health: "Healthy", onboarding: [], createdAt: new Date().toISOString(), documents: [] }];
  assert.equal((await put(api, library)).status, 200);
  const feed = { clientId: "synthetic-client", platform: "Meta Ads", account: "example-test", report: "Daily ads" };
  const csv = "date,campaign,ad,creative,audience,geography,product,clicks,impressions,spend,revenue\n2026-11-09,Launch,First ad,Short video,New users,India,Example,10,100,250,1000\n2026-11-10,Launch,Second ad,Short video,New users,India,Example,10,300,500,1500";
  const data = { action: "import", feed, currency: "INR", csv };
  assert.equal((await post(new TestBrowser(), data)).status, 401);
  assert.equal((await post(separate, data)).status, 404);
  assert.equal((await post(api, { ...data, csv: csv + "\n" + csv.split("\n")[1] })).status, 400);

  browser = await campaignBrowser();
  await browser.command("Network.enable");
  await browser.command("Network.setCookies", { cookies: [...api.cookies].map(([name, value]) => ({ name, value, url: api.base })) });
  await browser.command("Emulation.setDeviceMetricsOverride", { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
  await browser.command("Page.navigate", { url: api.base + "/analytics" });
  await browser.wait('document.body.innerText.includes("No measured rows for this view")', 60000);
  await browser.click("Data sources");
  await browser.wait('document.body.innerText.includes("Add a source report")');
  await browser.fill("Report client", feed.clientId);
  await browser.fill("Source account or property", feed.account);
  await browser.fill("Report name", feed.report);
  await browser.fill("Currency code", data.currency);
  temp = await mkdtemp(join(tmpdir(), "crm-analytics-csv-"));
  const filename = join(temp, "example-analytics.csv");
  await writeFile(filename, csv);
  const root = (await browser.command("DOM.getDocument")).root.nodeId;
  const input = (await browser.command("DOM.querySelector", { nodeId: root, selector: 'input[name="csv"]' })).nodeId;
  await browser.command("DOM.setFileInputFiles", { nodeId: input, files: [filename] });
  await browser.click("Import CSV report");
  await browser.wait('document.body.innerText.includes("Saved 2 measured rows")', 60000);
  const saved = (await read(laptop)).data.analyticsFeeds[0];
  assert.equal(saved.rows.length, 2);
  assert.equal((await read(separate)).data.analyticsFeeds.length, 0);
  assert.equal((await post(separate, { action: "remove", id: saved.id, updatedAt: saved.updatedAt })).status, 200);
  assert.equal((await read(api)).data.analyticsFeeds.length, 1);
  const forged = await read(api);
  forged.data.analyticsFeeds[0].rows[0].clicks = 999;
  assert.equal((await put(api, forged)).status, 409);
  assert.equal((await put(api, await read(api))).status, 200);
  await browser.click("Explore report");
  await browser.wait('document.body.innerText.includes("Breakdown table")');
  await browser.fill("Metric", "ctr");
  await browser.wait('document.body.innerText.includes("5%")');
  await browser.fill("Break down by", "product");
  await browser.wait('document.querySelector("tbody")?.innerText.includes("Example")');
  await mkdir("artifacts", { recursive: true });
  await browser.screenshot("artifacts/analytics-explorer-desktop.png");
  await browser.command("Emulation.setDeviceMetricsOverride", { width: 375, height: 812, deviceScaleFactor: 1, mobile: true });
  assert.equal(await browser.evaluate("document.documentElement.scrollWidth<=innerWidth"), true);
  await browser.fill("Data feed", "compare");
  await browser.wait('document.body.innerText.includes("Feed comparison")');
  assert.equal(await browser.evaluate("document.documentElement.scrollWidth<=innerWidth"), true);
  await browser.click("Data sources");
  await browser.wait('document.body.innerText.includes("Saved source reports")');
  assert.equal(await browser.evaluate("document.documentElement.scrollWidth<=innerWidth"), true);
  await browser.screenshot("artifacts/analytics-sources-mobile.png");
  const replace = { ...data, csv: csv.split("\n").slice(0, 2).join("\n").replace("First ad", "Replacement ad") };
  assert.equal((await post(api, replace)).status, 200);
  const replaced = (await read(laptop)).data.analyticsFeeds[0];
  assert.deepEqual(replaced.rows.map(row => row.ad), ["Replacement ad", "Second ad"]);
  const status = await (await api.request("/api/analytics")).json();
  if (!status.connectorReady) assert.equal((await post(api, { action: "sync", feed, start: "2026-11-09", end: "2026-11-10" })).status, 503);
  console.log("PASS: browser CSV upload, mobile explorer and sources, weighted metrics, date replacement, same-account visibility, protection and account isolation.");
} finally {
  await browser?.close();
  if (temp) { await rm(join(temp, "example-analytics.csv"), { force: true }); await rmdir(temp); }
  await Promise.all([account?.remove(), other?.remove()]);
}
