import assert from "node:assert/strict";
import {createTestAccount,TestBrowser} from "./reportAuthFixture.mjs";
import {campaignBrowser} from "./campaignBrowser.mjs";

let account,browser;
try{
  account=await createTestAccount();
  const api=new TestBrowser(),other=new TestBrowser();
  await Promise.all([api.signIn(account),other.signIn(account)]);
  const read=async client=>(await(await client.request("/api/crm/library")).json());
  browser=await campaignBrowser();
  await browser.command("Network.enable");
  await browser.command("Network.setCookies",{cookies:[...api.cookies].map(([name,value])=>({name,value,url:api.base}))});
  await browser.command("Emulation.setDeviceMetricsOverride",{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
  await browser.command("Page.navigate",{url:api.base+"/team"});
  await browser.wait('document.body.innerText.includes("Add team profile")');
  await browser.click("Add team profile");
  await browser.fill("Full name","Example Designer");
  await browser.fill("Email","synthetic-designer@example.com");
  await browser.fill("Title","Studio designer");
  await browser.fill("Weekly capacity (hours)","24");
  await browser.click("Add profile");
  await browser.wait('document.body.innerText.includes("Example Designer") && document.body.innerText.includes("24 h/wk")');
  await browser.wait('document.body.innerText.includes("CRM saved to your account")');
  const member=(await read(other)).data.team.find(person=>person.name==="Example Designer");
  assert.equal(member.capacityHours,24);
  assert.equal(member.status,"active");
  await browser.command("Page.navigate",{url:api.base+"/team?tab=permissions"});
  await browser.wait('!!document.querySelector("select[aria-label=\'Sales access to SEO\']")');
  await browser.fill("Sales access to SEO","read");
  await browser.wait('document.body.innerText.includes("Custom") && document.body.innerText.includes("CRM saved to your account")');
  assert.equal((await read(other)).data.permissionOverrides.sales.seo,"read");
  await browser.command("Page.navigate",{url:api.base+"/team?tab=time"});
  await browser.wait('document.body.innerText.includes("Record time")');
  await browser.fill("Team member",member.id);
  await browser.fill("Minutes worked","90");
  await browser.fill("Work note","Synthetic time log");
  await browser.click("Log time");
  await browser.wait('document.body.innerText.includes("Time saved.") && document.body.innerText.includes("1 h 30 min")');
  assert.equal((await read(other)).data.timeEntries[0].minutes,90);
  await browser.fill("Entry type","timer");
  await browser.click("Start timer");
  await browser.wait('document.body.innerText.includes("Timer started.")');
  const running=(await read(other)).data.timeEntries.find(entry=>entry.kind==="timer");
  assert.equal(running.endedAt,undefined);
  const bad=await read(other);
  bad.data.timeEntries.push({...running,id:crypto.randomUUID()});
  const rejected=await other.request("/api/crm/library",{method:"PUT",headers:{"content-type":"application/json"},body:JSON.stringify({...bad,operationId:crypto.randomUUID()})});
  assert.equal(rejected.status,400);
  await browser.click("Stop timer");
  await browser.wait('document.body.innerText.includes("Timer stopped.")');
  assert.ok((await read(other)).data.timeEntries.find(entry=>entry.kind==="timer").endedAt);
  await browser.command("Emulation.setDeviceMetricsOverride",{width:375,height:812,deviceScaleFactor:1,mobile:true});
  assert.equal(await browser.evaluate("document.documentElement.scrollWidth<=innerWidth"),true);
  await browser.command("Page.navigate",{url:api.base+"/team?tab=workload"});
  await browser.wait('document.body.innerText.includes("Logged this week") && document.body.innerText.includes("1 h 30 min")');
  assert.equal(await browser.evaluate("document.documentElement.scrollWidth<=innerWidth"),true);
  console.log("PASS: team profile and capacity, persisted permissions, manual time, durable timer, duplicate timer rejection, workload and mobile layout.");
}finally{
  await browser?.close();
  if(account)await account.remove();
}
